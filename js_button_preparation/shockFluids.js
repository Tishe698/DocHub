// shockFluids.js — общий текст о суммарном объёме кристаллоидов при шоке для записей NaCl 0,9%, раствора
// Рингера (infusion.js), Рингер-лактата и Стерофундина (electrolytes_solutions.js): одна формулировка во всех.
//
// Источники:
//  - ERC Guidelines 2025, Paediatric Life Support: болюсы по 10 мл/кг с переоценкой после каждого; суммарно
//    40–60 мл/кг за 1-й час может понадобиться при гиповолемическом или распределительном шоке; при
//    кардиогенном шоке объём индивидуален (болюсы по 5 мл/кг) — детский ориентир к нему не относится;
//  - КР МЗ РФ «Сепсис (у взрослых)» 2024 (ID 898_1), разд. 3.3: взрослым с сепсис-индуцированной
//    гипоперфузией в первые 3 часа — не более 30 мл/кг электролитного раствора (УДД 5, УУР С).
//
// Взрослый или ребёнок — по возрасту (с 18 лет — взрослый); возраст не указан (у записи нет поля) —
// обе строки: по массе взрослого от ребёнка не отличить (взрослый 45 кг, подросток 55 кг).

const ADULT_AGE = 18;
const ml = (v) => String(Math.round(v));

export function shockVolumeNotes(weightKg, ageYears) {
  const w = Number(weightKg);
  if (!(w > 0)) return [];
  const age = parseFloat(ageYears);
  const known = Number.isFinite(age) && age >= 0;
  const child = `Детям при гиповолемическом или распределительном (в том числе септическом) шоке — суммарно до 40–60 мл/кг (${ml(w * 40)}–${ml(w * 60)} мл) за 1-й час, с переоценкой после каждого болюса; при кардиогенном шоке этот объём не применять (ERC 2025).`;
  const adult = `Взрослым при сепсисе — не более 30 мл/кг (${ml(w * 30)} мл) за первые 3 часа (КР «Сепсис у взрослых», 2024).`;
  if (!known) return [child, adult];
  return [age < ADULT_AGE ? child : adult];
}
