// Поиск по всему списку: записи второй очереди не оттесняют препараты первой линии
// по запросам-показаниям, справочная запись не встаёт выше физраствора.
import formulas from '../formulas';
import { searchFormulas } from '../engine';

const first = (q) => searchFormulas(formulas, q)[0].formula.name;
const names = (q) => searchFormulas(formulas, q).map((r) => r.formula.name);

describe('приоритеты поиска', () => {
  test.each([
    ['эпилептический статус', 'Реланиум (диазепам)'],
    ['судороги', 'Реланиум (диазепам)'],
    ['противосудорожный', 'Реланиум (диазепам)'],
    ['натрия хлорид', 'Физраствор (натрия хлорид 0,9%)'],
    ['ингаляция', 'Пульмикорт (будесонид, небула)'],
    ['небулайзер', 'Пульмикорт (будесонид, небула)'],
    ['менингит', 'Цефтриаксон'],
    ['сепсис', 'Цефтриаксон'],
    ['антибиотик', 'Цефтриаксон'],
    ['аллергия', 'Супрастин (хлоропирамин)'],
    ['фибрилляция предсердий', 'Кордарон (амиодарон)'],
    ['адреналин', 'Адреналин (эпинефрин) — СЛР'],
  ])('«%s» → %s', (q, expected) => {
    expect(first(q)).toBe(expected);
  });

  test('«круп»: в выдаче и адреналин, и глюкокортикоиды первой линии', () => {
    const list = names('круп');
    expect(list).toEqual(
      expect.arrayContaining([
        'Адреналин (эпинефрин) — круп',
        'Дексаметазон',
        'Пульмикорт (будесонид, небула)',
      ]),
    );
  });

  test('новые записи находятся по своим названиям', () => {
    expect(first('тавегил')).toBe('Тавегил (клемастин)');
    expect(first('клафоран')).toBe('Цефотаксим');
    expect(first('пенициллин')).toBe('Бензилпенициллин');
    expect(first('кеппра')).toBe('Кеппра (леветирацетам)');
    expect(first('феназепам')).toBe('Феназепам (бромдигидрохлорфенилбензодиазепин)');
    expect(first('маннитол')).toBe('Маннитол');
    expect(first('дигоксин')).toBe('Дигоксин');
    expect(first('гелофузин')).toBe('Гелофузин (желатин сукцинилированный)');
    expect(first('бронхиолит')).toBe('Гипертонический раствор (натрия хлорид 3%) — бронхиолит');
  });
});
