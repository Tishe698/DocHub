// Похожие на сокращения токены: два и более заглавных символа (кириллица или латиница),
// в том числе смешанные со строчными (ИМпST, BNFc, GeneReviews). Единицы через дробь
// («мг/кг», «в/в») сюда не попадают: они начинаются со строчной буквы.
export const TOKEN_RE =
  /(?<![А-Яа-яЁёA-Za-z])([А-ЯЁA-Z][А-ЯЁA-Zа-яёa-z0-9]*[А-ЯЁA-Z][А-ЯЁA-Zа-яёa-z0-9]*)(?![а-яё])/g;

// Все токены-сокращения в текстах (для теста полноты словаря)
export const abbreviationTokens = (texts) => {
  const out = new Set();
  for (const t of texts) {
    if (typeof t !== 'string') continue;
    for (const m of t.matchAll(TOKEN_RE)) out.add(m[1]);
  }
  return [...out];
};

// Сокращения с расшифровкой, найденные в текстах, — в порядке первого появления
export const findAbbreviations = (texts) =>
  abbreviationTokens(texts)
    .filter((t) => Object.prototype.hasOwnProperty.call(ABBREVIATIONS, t))
    .map((abbr) => ({ abbr, full: ABBREVIATIONS[abbr] }));

// Видимые тексты записи до расчёта: название, форма выпуска, предупреждения, подписи и варианты выбора
export const formulaTexts = (formula) => {
  if (!formula) return [];
  const texts = [formula.name, formula.description, ...(formula.warnings || [])];
  Object.values(formula.labels || {}).forEach((l) => texts.push(l));
  Object.values(formula.inputs || {}).forEach((input) => {
    if (typeof input === 'string') texts.push(input);
    else if (input && typeof input === 'object') {
      texts.push(input.label);
      (input.choices || []).forEach((c) => texts.push(c.label));
    }
  });
  return texts.filter((t) => typeof t === 'string');
};
