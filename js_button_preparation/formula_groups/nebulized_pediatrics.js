import { routeInput } from '../routes';

const num = (x, digits = 2) => String(Number(x.toFixed(digits))).replace('.', ',');
const weightOf = (x) => parseFloat(x) || 0;
// «1 ампула», «2 ампулы», «5 ампул»
const ampoules = (n) => {
  const d = n % 10;
  const dd = n % 100;
  if (d === 1 && dd !== 11) return `${n} ампула`;
  if (d >= 2 && d <= 4 && (dd < 12 || dd > 14)) return `${n} ампулы`;
  return `${n} ампул`;
};
const ageOf = (a) => {
  const n = parseFloat(a);
  return Number.isFinite(n) && n >= 0 ? n : NaN;
};

/** ------------------------------ Адреналин при крупе ------------------------------ **/

const EPI_CONC = 1; // мг/мл — раствор 1:1000 (0,1%)
const EPI_ML_PER_KG = 0.5;
const EPI_MAX_ML = 5; // КР 352_2: 5 мл на ингаляцию
const EPI_ADULT_YEARS = 18; // КР — дети

const epinephrineCroup = ({ weight, ageYears, route = 'inh' }) => {
  if (route !== 'inh') return {};
  const w = weightOf(weight);
  if (!(w > 0)) return {};
  const age = ageOf(ageYears);
  // КР 352_2 — для детей; взрослым запись не считает
  if (!Number.isFinite(age) || age >= EPI_ADULT_YEARS) return {};
  const ml = Math.min(w * EPI_ML_PER_KG, EPI_MAX_ML);
  const notes = [];
  if (w * EPI_ML_PER_KG < EPI_MAX_ML) {
    notes.push(
      `КР дают 5 мл на ингаляцию независимо от массы; расчёт ${num(EPI_ML_PER_KG, 1)} мл/кг — более осторожный вариант для ребёнка до 10 кг`,
    );
  }
  notes.push(`${num(ml, 2)} мл раствора 1 мг/мл — это ${ampoules(Math.ceil(ml - 1e-9))} по 1 мл`);
  return {
    result1: ml,
    result2: ml * EPI_CONC,
    result3:
      'Через небулайзер (компрессорный или меш), раствор 1 мг/мл без разведения; если объём меньше 3 мл — довести NaCl 0,9% до 3 мл (заполнение камеры). Эффект через 10–30 мин, держится не более 2 ч — затем возможно усиление стеноза: наблюдение не менее 3 ч, госпитализация. Повтор — только по решению врача.',
    result4: `${notes.map((n) => n.charAt(0).toUpperCase() + n.slice(1)).join('. ')}.`,
  };
};

