// Число без «хвоста» плавающей точки для строковых примечаний (0.15000000000000002 → 0.15)
const num = (x, digits = 3) => String(Number(x.toFixed(digits)));

// Скорость шприцевого насоса, мл/ч = доза (мкг/кг/мин) × вес × 60 / концентрация (мкг/мл)
const pumpRate = (mcgPerMin, drugMg, volumeMl) => {
  const concMcgPerMl = (drugMg * 1000) / volumeMl;
  return { concMcgPerMl, mlPerHour: (mcgPerMin * 60) / concMcgPerMl };
};

