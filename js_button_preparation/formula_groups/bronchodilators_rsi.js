// Флаконы на дозу: наименьший набор из 500 и 200 мг, покрывающий дозу
const sugVials = (mg) => {
  let best = null;
  for (let n500 = 0; n500 <= Math.ceil(mg / 500) + 1; n500 += 1) {
    const n200 = Math.max(0, Math.ceil((mg - n500 * 500) / 200 - EPS));
    const total = n500 * 500 + n200 * 200;
    if (!best || total < best.total || (total === best.total && n500 + n200 < best.n))
      best = { total, n: n500 + n200, n500, n200 };
  }
  const parts = [];
  if (best.n500) parts.push(`${best.n500} × 500 мг (5 мл)`);
  if (best.n200) parts.push(`${best.n200} × 200 мг (2 мл)`);
  return parts.join(' + ');
};

