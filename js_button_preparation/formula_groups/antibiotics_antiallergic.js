/** ------------------------------ Цефтриаксон ------------------------------ **/

// Текст введения цефтриаксона по пути. dose — мг на одно введение, w — кг, months — возраст.
// ГРЛС «Цефтриаксон», разд. «Правила приготовления и введения растворов».
export const ceftriaxoneAdministration = (route, dose, w, months, indication) => {
  const parts = [];
  if (route === 'im') {
    // ОХЛП «Роцефин» (2026): лидокаин как растворитель запрещён детям младше 15 лет — вода для инъекций.
    // ГРЛС Цефтриаксон-КМП: в/м 1 г в 3,6 мл воды для инъекций (около 250 мг/мл); 1% лидокаин — для уменьшения боли.
    if (months < 15 * 12) {
      parts.push(
        'В/м глубоко в ягодичную мышцу: 0,5 г в 2 мл, 1 г в 3,5 мл воды для инъекций (до 15 лет лидокаин как растворитель не применяют).',
      );
    } else {
      parts.push(
        'В/м глубоко в ягодичную мышцу: 0,5 г в 2 мл, 1 г в 3,5 мл 1% лидокаина (исключить противопоказания к лидокаину) или воды для инъекций. Раствор с лидокаином в/в не вводить.',
      );
    }
    // ГРЛС: не более 1 г в одну мышцу
    if (dose > 1000) {
      parts.push(
        `Не более 1 г в одну мышцу: дозу разделить на ${Math.ceil(dose / 1000)} инъекции в разные мышцы.`,
      );
    } else {
      parts.push('Не более 1 г в одну мышцу.');
    }
    // КР 58 (2023), разд. 3.1: при септическом шоке в/м введение не достигает системного эффекта
    if (indication === 'meningitis')
      parts.push('При септическом шоке в/м не вводить — только в/в или в/к.');
    return parts.join(' ');
  }
  // КР 58 (2023), разд. 3.1: при ГМИ с септическим шоком — только в/в (в/к) введение; доза и раствор — как в/в
  if (route === 'io')
    parts.push('В/к — доза и раствор как для в/в, только при невозможности в/в доступа.');
  // ГРЛС: дозы от 50 мг/кг — только капельно не менее 30 мин; 2 г в 40 мл раствора без кальция
  const perKg = w > 0 ? dose / w : 0;
  if (perKg >= 50 - 1e-9) {
    parts.push(
      'Капельно не менее 30 мин (доза от 50 мг/кг): 2 г в 40 мл раствора без кальция (0,9% натрия хлорид или 5–10% декстроза), 50 мг/мл.',
    );
  } else {
    parts.push(
      'Струйно медленно, 2–4 мин: 0,5 г в 5 мл, 1 г в 10 мл воды для инъекций (100 мг/мл); или капельно 30 мин (2 г в 40 мл раствора без кальция).',
    );
  }
  // ГРЛС, ОХЛП «Роцефин»: раствор Рингера и Хартмана содержат кальций
  parts.push('Раствор Рингера и другие растворы с кальцием не использовать.');
  return parts.join(' ');
};

