// Инструкция ГРЛС «Актилизе»: лиофилизат 50 мг + растворитель (вода для инъекций) 50 мл →
// 1 мг/мл; допускается дальнейшее разведение 0,9% NaCl до 0,2 мг/мл, не разводить водой и глюкозой.
const ALT_CONC = 1; // мг/мл
const ALT_DESC =
  'Лиофилизат для приготовления раствора для инфузий 50 мг + растворитель 50 мл (вода для инъекций) → 1 мг/мл; объём посчитан на 1 мг/мл. Только в/в. Входит в укладку общепрофильную и специализированную СМП (приказ МЗ РФ № 1165н; с 01.01.2027 — № 424н)';
// Порог массы 65 кг и предел 1,5 мг/кг: инструкция ГРЛС «Актилизе» и КР ИМпST 2024, прил. А3
const ALT_LOW_WEIGHT = 65;
const ALT_MAX_MG = 100;

// 90-минутная (ускоренная) схема, начало в пределах 6 ч (КР ИМпST 2024, прил. А3; инструкция ГРЛС):
// 15 мг струйно; 50 мг за 30 мин; 35 мг за 60 мин. Масса < 65 кг: 0,75 мг/кг (не более 50 мг) за 30 мин,
// затем 0,5 мг/кг (не более 35 мг) за 60 мин.
const alteplaseAccelerated = (w) => {
  const low = w < ALT_LOW_WEIGHT;
  const inf1 = low ? Math.min(0.75 * w, 50) : 50;
  const inf2 = low ? Math.min(0.5 * w, 35) : 35;
  const total = 15 + inf1 + inf2;
  const notes = [
    low
      ? 'масса менее 65 кг: инфузия 0,75 мг/кг (не более 50 мг) за 30 мин, затем 0,5 мг/кг (не более 35 мг) за 60 мин'
      : 'масса 65 кг и более: фиксированная схема 15 + 50 + 35 мг, предел 100 мг',
    'объём = доза в мг (раствор 1 мг/мл)',
  ];
  return {
    result1: 15,
    result2: 15 / ALT_CONC,
    result3: inf1,
    result4: (inf1 / ALT_CONC) * 2, // за 30 мин → мл/ч
    result5: inf2,
    result6: inf2 / ALT_CONC, // за 60 мин → мл/ч
    result7: total,
    result8: sentence(notes),
  };
};

// 3-часовая схема, начало через 6–12 ч (КР ИМпST 2024, прил. А3; инструкция ГРЛС): 10 мг струйно; 50 мг
// инфузией за 1-й час; далее по 10 мг за 30 мин (20 мг/ч) до суммарной 100 мг за 3 ч. Масса < 65 кг —
// суммарно не более 1,5 мг/кг: распределение в источниках не расписано, поэтому схема просто
// обрывается по достижении предела (сначала сокращается последняя часть, затем инфузия 1-го часа).
const alteplase3h = (w) => {
  const low = w < ALT_LOW_WEIGHT;
  const totalRaw = low ? 1.5 * w : ALT_MAX_MG;
  const total = Math.min(totalRaw, ALT_MAX_MG);
  const bolus = Math.min(10, total);
  const firstHour = Math.min(50, total - bolus);
  const rest = Math.max(0, total - bolus - firstHour);
  const restHours = rest / 20;
  const res = {
    result9: bolus,
    result10: firstHour,
    result11: firstHour / ALT_CONC, // за 60 мин → мл/ч
    result14: total,
  };
  const notes = [];
  if (rest > 0) {
    res.result12 = rest;
    res.result13 = 20 / ALT_CONC; // 10 мг за 30 мин
    notes.push(
      `затем ${num(rest, 1)} мг со скоростью 10 мг за 30 мин (20 мл/ч) — ${num(restHours, 2)} ч`,
    );
  } else {
    notes.push('после инфузии 1-го часа введение закончено — достигнут предел 1,5 мг/кг');
  }
  notes.push(
    low
      ? `масса менее 65 кг: суммарно не более 1,5 мг/кг = ${num(total, 1)} мг; схема обрывается по достижении предела`
      : 'суммарно 100 мг за 3 ч',
  );
  notes.push('объём = доза в мг (раствор 1 мг/мл)');
  res.result15 = sentence(notes);
  return res;
};

