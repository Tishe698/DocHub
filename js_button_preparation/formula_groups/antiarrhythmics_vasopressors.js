// Число для текста примечания: запятая, без «хвоста» плавающей точки
const num = (x, digits = 2) => String(Number(x.toFixed(digits))).replace('.', ',');
const toNum = (x) => parseFloat(x);
const weightOf = (x) => toNum(x) || 0;
// Возраст из поля: неотрицательное число или NaN
const ageOf = (a) => {
  const n = toNum(a);
  return Number.isFinite(n) && n >= 0 ? n : NaN;
};
// Сравнение возраста в долях года без ошибки плавающей точки (1/12 из движка)
const EPS = 1e-9;
// Примечания одной фразой: через «; », с заглавной буквы и точкой в конце
const sentence = (notes) => {
  const text = notes.join('; ');
  return text.charAt(0).toUpperCase() + text.slice(1) + '.';
};

// Все три препарата группы по инструкциям ГРЛС противопоказаны до 18 лет
const ADULT_AGE = 18;
const isAdult = (age) => Number.isFinite(age) && age >= ADULT_AGE - EPS;

// Укладки СМП: № 1165н (до 01.01.2027) и № 424н (с 01.01.2027) — общепрофильная и реанимационная
const KIT = 'В укладке СМП (приказы МЗ РФ № 1165н до 01.01.2027 и № 424н с 01.01.2027)';

/** ------------------------------ Новокаинамид (прокаинамид) ------------------------------ **/

const PROC_CONC = 100; // мг/мл — раствор 10%
// КР «ФП и ТП» 2025, табл. П12: струйно по 100 мг каждые 5 мин до суммарной 500 мг
const PROC_STEP_MG = 100;
const PROC_BOLUS_TOTAL_MG = 500;
// КР «ФП и ТП» 2025, табл. П12: «максимальная нагрузочная доза 1000 мг (10 мл)»; инструкция ГРЛС
// (Органика): высшая разовая доза 1 г, суточная 3 г
const PROC_MAX_MG = 1000;
// AHA 2020 ACLS: нагрузка до «maximum dose 17 mg/kg» — предел по массе (в источниках РФ его нет);
// строже 1000 мг при массе < 59 кг
const PROC_MAX_PER_KG = 17;
// КР «ФП и ТП» 2025, табл. П12: 10 мл препарата + 40 мл 0,9% NaCl = 1000 мг / 50 мл = 20 мг/мл,
// скорость 1 мл/мин = 20 мг/мин
const PROC_INF_CONC = 20; // мг/мл
const PROC_INF_MG_MIN = 20;

const procainamide = ({ weight, ageYears }) => {
  const w = weightOf(weight);
  if (!(w > 0)) return {};
  if (!isAdult(ageOf(ageYears))) return {};
  const byWeight = w * PROC_MAX_PER_KG;
  const maxMg = Math.min(PROC_MAX_MG, byWeight);
  const bolusTotal = Math.min(PROC_BOLUS_TOTAL_MG, maxMg);
  const notes = [];
  if (byWeight < PROC_MAX_MG) {
    notes.push(
      `достигнут предел по массе 17 мг/кг = ${num(byWeight, 0)} мг (AHA 2020; строже предела 1000 мг КР и инструкции РФ)`,
    );
  } else {
    notes.push('максимальная нагрузочная доза 1000 мг (10 мл) — КР «ФП и ТП» 2025, инструкция РФ');
  }
  // Инструкция ГРЛС (Органика): при сердечной недостаточности II ст. дозу уменьшают на 1/3 и более
  notes.push('при сердечной недостаточности II ст. дозу уменьшить на ⅓ и более (инструкция РФ)');
  return {
    result1: PROC_STEP_MG,
    result2: PROC_STEP_MG / PROC_CONC,
    result3: bolusTotal,
    result4: maxMg,
    result5: maxMg / PROC_CONC,
    // 20 мг/мин при 20 мг/мл = 1 мл/мин = 60 мл/ч
    result6: (PROC_INF_MG_MIN / PROC_INF_CONC) * 60,
    // КР «ФП и ТП» 2025, табл. П12; инструкция ГРЛС: перед в/в введением разводить (5% глюкоза или
    // 0,9% NaCl), не быстрее 50 мг/мин, под постоянным контролем ЧСС, АД и ЭКГ
    result7:
      `1) в/в струйно медленно по 100 мг (1 мл 10%, разведённого 0,9% NaCl или 5% глюкозой) каждые 5 мин, не быстрее 50 мг/мин, до купирования или суммарной ${num(bolusTotal, 0)} мг. ` +
      `2) Нет эффекта через 10 мин — капельно: 10 мл (1000 мг) + 40 мл 0,9% NaCl = 20 мг/мл, 1 мл/мин (20 мг/мин, ≈ 20 кап/мин) 25–30 мин — до суммарной 500–600 мг, всего не более ${num(maxMg, 0)} мг. Под контролем АД, ЧСС и ЭКГ.`,
    // КР «ФП и ТП» 2025, табл. П12: ЭКГ-основания для снижения дозы или отмены; инструкция ГРЛС: при
    // быстром в/в введении — коллапс, асистолия
    result8:
      'Снижение АД, расширение QRS > 25% от исходного, QT > 500 мс, ЧСС < 50 в мин, подъём ST по типу Бругада.',
    result9: sentence(notes),
  };
};

/** ------------------------------ Пропанорм (пропафенон) ------------------------------ **/

const PROPAF_CONC = 3.5; // мг/мл — раствор для в/в введения, ампулы 10 мл (35 мг)
// Инструкция ГРЛС «Пропанорм» р-р (ЛП-002948): в/в струйно 1,5–2 мг/кг за 10 мин; повтор через 90–120 мин;
// максимальная суточная доза 560 мг. КР «ФП и ТП» 2025, табл. П12 — та же схема
const PROPAF_IV_LOW = 1.5;
const PROPAF_IV_HIGH = 2;
const PROPAF_DAY_MAX_MG = 560;
// Таблетки «Пропанорм»: нагрузочная доза для купирования пароксизма ФП 600 мг однократно (инструкция
// ГРЛС); старше 70 лет и при массе < 70 кг — меньшие дозы (там же). КР «ФП и ТП» 2025, тезис 3.1.2.2.1 и
// табл. П12: #пропафенон внутрь 450–600 мг однократно. Меньшая доза — нижняя граница КР, 450 мг
const PROPAF_PO_MG = 600;
const PROPAF_PO_REDUCED_MG = 450;

const propafenoneIv = (w) => {
  const lowRaw = w * PROPAF_IV_LOW;
  const highRaw = w * PROPAF_IV_HIGH;
  const low = Math.min(lowRaw, PROPAF_DAY_MAX_MG);
  const high = Math.min(highRaw, PROPAF_DAY_MAX_MG);
  const notes = [
    'расчёт по нижней границе 1,5 мг/кг; при необходимости — до 2 мг/кг (инструкция РФ, КР «ФП и ТП» 2025)',
  ];
  if (highRaw > PROPAF_DAY_MAX_MG) notes.push('достигнут предел 560 мг в сутки');
  notes.push(
    `объём — по раствору 3,5 мг/мл, ампула 10 мл = 35 мг: ${num(low / PROPAF_CONC / 10, 1)} амп. на ${num(low, 0)} мг`,
  );
  return {
    result1: low,
    result2: low / PROPAF_CONC,
    result3: high,
    result4: high / PROPAF_CONC,
    // Инструкция ГРЛС (р-р): разводить только 5% глюкозой — с 0,9% NaCl возможен осадок
    result5: `в/в струйно медленно за 10 мин (≈ ${num(low / 10, 1)} мг/мин) под контролем ЭКГ и АД. Если разводить — только 5% глюкозой: с 0,9% NaCl выпадает осадок.`,
    result6:
      'Нет эффекта — ту же дозу повторно через 90–120 мин; всего не более 560 мг в сутки (160 мл).',
    result7: sentence(notes),
  };
};

const propafenonePo = (w, age) => {
  const reduced = w < 70 || age > 70 + EPS;
  const mg = reduced ? PROPAF_PO_REDUCED_MG : PROPAF_PO_MG;
  const res = {
    result11: mg,
    result12: mg / 150,
    result14:
      // Инструкция ГРЛС (таблетки): внутрь после еды, проглатывать целиком; КР 2025 — одномоментный приём
      'внутрь однократно (всю дозу сразу) после еды, таблетки проглотить целиком.',
  };
  if (mg === PROPAF_PO_MG) res.result13 = mg / 300;
  res.result15 = reduced
    ? 'Масса < 70 кг или возраст > 70 лет — меньшая доза 450 мг (инструкция РФ: «меньшие дозы»; КР 2025: 450–600 мг).'
    : '600 мг — нагрузочная доза инструкции РФ для купирования пароксизма ФП (КР 2025: 450–600 мг).';
  return res;
};

/** ------------------------------ Мезатон (фенилэфрин) ------------------------------ **/

const PHE_CONC = 10; // мг/мл — раствор 1%
// Инструкция ГРЛС «Мезатон»: при коллапсе в/в разово 0,1–0,5 мл 1% (1–5 мг); высшая доза в/в — разовая
// 5 мг, суточная 25 мг
const PHE_IV_LOW_MG = 1;
const PHE_IV_MAX_MG = 5;
const PHE_IV_DAY_MG = 25;
// Там же: в/м и п/к разово 0,3–1,0 мл 1% (3–10 мг); высшая доза — разовая 10 мг, суточная 50 мг
const PHE_IM_LOW_MG = 3;
const PHE_IM_MAX_MG = 10;
const PHE_IM_DAY_MG = 50;
// Там же: капельно 1 мл 1% (10 мг) в 250–500 мл 5% глюкозы; начальная скорость 180 мкг/мин, затем 30–60
// мкг/мин. Расчёт на 250 мл: 10 мг / 250 мл = 40 мкг/мл
const PHE_INF_MCG_ML = 10000 / 250;
const pheMlH = (mcgMin) => (mcgMin / PHE_INF_MCG_ML) * 60;
// Капли: стандартная система 20 кап/мл
const dropsMin = (mlH) => Math.round((mlH * 20) / 60);

const phenylephrine = ({ route, ageYears }) => {
  if (!isAdult(ageOf(ageYears))) return {};
  if (route === 'im' || route === 'sc') {
    const path = route === 'im' ? 'в/м' : 'п/к';
    return {
      result11: PHE_IM_LOW_MG,
      result12: PHE_IM_LOW_MG / PHE_CONC,
      result13: PHE_IM_MAX_MG,
      result14: PHE_IM_MAX_MG / PHE_CONC,
      result15: `${path}; действие через 10–15 мин, длится 1–2 ч. Не более ${PHE_IM_DAY_MG} мг в сутки (инструкция РФ).`,
    };
  }
  const start = pheMlH(180);
  const lo = pheMlH(30);
  const hi = pheMlH(60);
  return {
    result1: PHE_IV_LOW_MG,
    result2: PHE_IV_LOW_MG / PHE_CONC,
    result3: PHE_IV_MAX_MG,
    result4: PHE_IV_MAX_MG / PHE_CONC,
    // Инструкция ГРЛС: разовую дозу развести в 20 мл 5% глюкозы или 0,9% NaCl, струйно медленно; повтор,
    // если САД снова 70–80 мм рт. ст., не чаще чем через 15 мин
    result5:
      'в/в струйно медленно: разовую дозу развести в 20 мл 0,9% NaCl или 5% глюкозы. Повтор — если САД снова 70–80 мм рт. ст., не раньше чем через 15 мин.',
    result6: start,
    result7: lo,
    result8: hi,
    result9: `Капельно: 1 мл 1% (10 мг) + 250 мл 5% глюкозы = 40 мкг/мл. Старт 180 мкг/мин = ${num(start, 0)} мл/ч (≈ ${dropsMin(start)} кап/мин), затем 30–60 мкг/мин = ${num(lo, 0)}–${num(hi, 0)} мл/ч (≈ ${dropsMin(lo)}–${dropsMin(hi)} кап/мин). На 500 мл скорость в мл/ч — вдвое больше.`,
    // Инструкция ГРЛС: высшая суточная доза в/в — 25 мг; отмена после длительной инфузии — постепенно
    result10: `Не более ${PHE_IV_DAY_MG} мг в/в в сутки (инструкция РФ): при 30–60 мкг/мин — это 7–14 ч инфузии. После длительной инфузии снижать скорость постепенно.`,
  };
};

