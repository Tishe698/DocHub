import { routeInput, choiceInput } from '../routes';

// Число для текста примечания: без «хвоста» плавающей точки
const n = (x, d = 2) => String(+x.toFixed(d));

// Число из поля; пусто/не число → NaN (такой ввод не считается)
const num = (v) => {
  const x = typeof v === 'number' ? v : parseFloat(v);
  return Number.isFinite(x) ? x : NaN;
};
const validWeight = (w) => Number.isFinite(w) && w > 0;
const validAge = (a) => Number.isFinite(a) && a >= 0;

// Значение поля-выбора: одно из вариантов, иначе — значение по умолчанию
const pick = (input, value) =>
  input.choices.some((c) => c.value === value) ? value : input.default;

// Новорождённый — младше 1 мес. (возраст < 1/12 года, как его передаёт движок)
const NEONATE_YEARS = 1 / 12;

/** ---------------- Поля выбора ---------------- **/

// Дротаверин: в/м, п/к, в/в — инструкции «Дротаверин, р-р для в/в и в/м введения 20 мг/мл» (Биомед им. Мечникова)
// и «Но-шпа, р-р для в/в и в/м введения» (ГРЛС); доза для всех путей одна, различается техника введения
const DROTAVERINE_ROUTE = routeInput(['im', 'iv', 'sc'], 'im');

// Налоксон: в/в, в/м, п/к — инструкция «Налоксон, р-р для инъекций 0.4 мг/мл» (МЭЗ, ГРЛС);
