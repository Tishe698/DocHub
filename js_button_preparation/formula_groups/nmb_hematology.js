// Округление до сотых/десятых для текстовых примечаний (числовые результаты округляет движок)
const r2 = (v) => String(Math.round(v * 100) / 100);
const r1 = (v) => String(Math.round(v * 10) / 10);

// Число ≥ 0 из поля; иначе NaN (пустой/неверный ввод)
const num = (x) => {
  const n = parseFloat(x);
  return Number.isFinite(n) && n >= 0 ? n : NaN;
};

// Значение поля-выбора: пусто — по умолчанию из inputs; неизвестное — null (расчёт не выполняется)
const pick = (input, value) => {
  const v = value === undefined || value === null || value === '' ? input.default : String(value);
  return input.choices.some((c) => c.value === v) ? v : null;
};

