// Возраст в месяцах из двух полей. Возвращает { months } или { error: 'текст' }.
const ageInMonths = (ageYears, ageMonths) => {
  const y = Math.max(0, parseFloat(ageYears) || 0);
  const m = Math.max(0, parseFloat(ageMonths) || 0);
  // Месяцы сверх полных лет — 0–11; иначе поля противоречат друг другу
  if (y > 0 && m >= 12) {
    return { error: 'Месяцы указываются сверх полных лет: от 0 до 11. Проверьте возраст.' };
  }
  return { months: y * 12 + m };
};

