const PROT_CONC = 10; // мг/мл
const PROT_MAX_10MIN = 50; // инструкции ГРЛС: не более 50 мг в первые 10 мин
const PROT_MAX_HOUR = 150; // инструкции ГРЛС: не более 150 мг за 1 ч
// Инструкция ГРЛС «Клексан»: 100 мг/мл эноксапарина = 10 000 анти-Xa МЕ/мл, т. е. 1 мг = 100 МЕ
const ENOX_IU_PER_MG = 100;
const PROT_UNITS_WARN_MIN = 500; // ниже — вероятно, введены мг эноксапарина вместо МЕ

const protamine = ({ scenario, heparin, ageYears }) => {
  const s = PROTAMINE.parse(scenario);
  if (!s) return {};
  // Инструкции ГРЛС: детский возраст — противопоказание
  if (!isAdult(ageOf(ageYears))) return {};
  const notes = [];
  let lo;
  let hi;
  if (s.fixed) {
    // Инструкция ГРЛС: при инфузии гепарина — прекратить инфузию, 25–30 мг; расчёт по нижней границе
    [lo, hi] = s.fixed;
    notes.push(
      'при инфузии гепарина доза не зависит от введённого количества: остановить инфузию, 25–30 мг',
    );
  } else {
    const u = toNum(heparin);
    if (!(u > 0)) return {};
    lo = (u / 100) * s.ratio[0];
    hi = (u / 100) * s.ratio[1];
    notes.push(
      s.ratio[0] === s.ratio[1]
        ? `${num(s.ratio[0], 3)} мг на 100 МЕ анти-Xa (инструкция РФ)`
        : `${num(s.ratio[0], 3)}–${num(s.ratio[1], 3)} мг на 100 ЕД (инструкция РФ), расчёт по нижней границе: избыток протамина сам нарушает гемостаз`,
    );
  }
  const mg = Math.min(lo, PROT_MAX_10MIN);
  if (lo > PROT_MAX_10MIN) {
    notes.push(
      `достигнут предел 50 мг за 10 мин (расчёт ${num(lo, 0)} мг); остаток — по АЧТВ/АВС, не более ${PROT_MAX_HOUR} мг за 1 ч`,
    );
  }
  if (s.value.startsWith('lmwh')) {
    notes.push(
      `доза НМГ вводится в МЕ анти-Xa: 1 мг эноксапарина = ${ENOX_IU_PER_MG} МЕ (80 мг = 8000 МЕ)`,
    );
    const u = toNum(heparin);
    if (u < PROT_UNITS_WARN_MIN)
      notes.push(
        `введено ${num(u, 1)} — если это мг эноксапарина, введите ${num(u * ENOX_IU_PER_MG, 0)} МЕ`,
      );
    notes.push('анти-Xa активность нейтрализуется не более чем на 60%');
  }
  return {
    result1: mg,
    result2: mg / PROT_CONC,
    result3:
      lo === hi ? `${num(lo, 1)} мг.` : `${num(lo, 1)}–${num(hi, 1)} мг по таблице инструкции.`,
    // Инструкции ГРЛС: 1 мл (10 мг) за 3 мин; повтор через 15–30 мин под контролем свёртываемости
    result4:
      'в/в струйно медленно: 1 мл (10 мг) за 3 мин. Повтор через 15–30 мин — по АЧТВ или АВС.',
    result5: sentence(notes),
  };
};

