// Инструкции ГРЛС (Мосфарм, Биохимик): детям старше 12 лет — не более 15 мг/кг; до 12 лет противопоказан
const PROCAINE_CHILD_MG_KG = 15;
const PROCAINE_MIN_AGE = 12;
const procaineAdultMaxMg = (s) => s.conc * s.maxMl;

const procaine = ({ solution, weight, ageYears }) => {
  const w = weightOf(weight);
  if (!(w > 0)) return {};
  const s = PROCAINE.parse(solution);
  if (!s) return {};
  const age = ageOf(ageYears);
  if (!Number.isFinite(age) || age < PROCAINE_MIN_AGE - EPS) return {};
  const adultMax = procaineAdultMaxMg(s);
  const notes = [];
  let mg;
  if (isAdult(age)) {
    mg = adultMax;
    notes.push(
      `взрослым первая разовая доза — не более ${s.maxMl} мл ${s.label.split(' ')[0]} (${num(adultMax, 0)} мг; инструкция РФ), предел не зависит от массы`,
    );
    // Инструкция Мосфарм: с осторожностью старше 65 лет, при почечной недостаточности и болезнях печени
    notes.push('старше 65 лет, при болезнях почек и печени — с осторожностью');
    // Биохимик: далее каждый час операции — не более 2 г (400 мл 0,5%)
    notes.push('при продолжении — не более 2 г за каждый следующий час (инструкция Биохимик)');
  } else {
    const raw = w * PROCAINE_CHILD_MG_KG;
    mg = Math.min(raw, adultMax);
    notes.push('12–17 лет — не более 15 мг/кг (инструкция РФ), с осторожностью');
    if (raw > adultMax) notes.push(`ограничено взрослым пределом ${num(adultMax, 0)} мг`);
  }
  return {
    result1: mg,
    result2: mg / s.conc,
    // Инструкции ГРЛС: эпинефрин 0,1% — 1 капля на 2–10 мл раствора для удлинения действия
    result3: `местно: ${s.value === '2' ? 'проводниковая анестезия' : 'инфильтрация или блокада'}, перед каждым введением — аспирационная проба. Для удлинения действия допустим эпинефрин 0,1% — 1 капля на 2–10 мл раствора.`,
    result4: sentence(notes),
  };
};

