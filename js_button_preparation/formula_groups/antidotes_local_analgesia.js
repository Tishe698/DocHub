// КР «Токсическое действие метанола и этиленгликоля» 2024, табл. 1 (взрослые): основная (нагрузочная)
// доза в мл/кг и поддерживающая в мл/кг/ч — без гемодиализа и на фоне гемодиализа
const ETHANOL = optionInput(
  'Раствор этанола',
  [
    {
      value: 'iv10',
      route: 'iv',
      label: '10%',
      conc: 10,
      load: 7.5,
      maint: [1, 2],
      dial: [2, 3.5],
    },
    { value: 'iv5', route: 'iv', label: '5%', conc: 5, load: 15, maint: [2, 4], dial: [4, 7] },
    { value: 'po40', route: 'po', label: '40%', conc: 40, load: 2, maint: [0.25], dial: [0.5] },
    { value: 'po20', route: 'po', label: '20%', conc: 20, load: 4, maint: [0.5], dial: [1] },
    { value: 'po10', route: 'po', label: '10%', conc: 10, load: 7.5, maint: [1], dial: [2] },
    { value: 'po5', route: 'po', label: '5%', conc: 5, load: 15, maint: [2], dial: [4] },
  ],
  'iv10',
);
const ETHANOL_DENSITY = 0.789; // г/мл — для пересчёта объёма раствора в граммы этанола в примечании

const ethanol = ({ solution, dialysis, weight, ageYears }) => {
  const w = weightOf(weight);
  if (!(w > 0)) return {};
  const s = ETHANOL.parse(solution);
  if (!s) return {};
  // КР 2024: таблица доз — только для взрослых; у детей единичные наблюдения — не рассчитываем
  if (!isAdult(ageOf(ageYears))) return {};
  const onDialysis = dialysis === 'yes';
  const rate = onDialysis ? s.dial : s.maint;
  const loadMl = w * s.load;
  const res = { result1: loadMl, result2: w * rate[0] };
  if (rate.length > 1) res.result3 = w * rate[1];
  const gPerKg = (s.load * s.conc * ETHANOL_DENSITY) / 100;
  res.result4 =
    s.route === 'iv'
      ? `в/в: нагрузочная ${num(s.load, 1)} мл/кг ${s.conc}% раствора, затем поддерживающая инфузия ${rate.map((r) => num(r, 2)).join('–')} мл/кг/ч.`
      : `внутрь: нагрузочная ${num(s.load, 1)} мл/кг ${s.conc}% раствора, затем ${num(rate[0], 2)} мл/кг каждый час.`;
  const notes = [
    `нагрузочная ≈ ${num(gPerKg, 2)} г/кг этанола (${num(gPerKg * w, 0)} г)`,
    onDialysis
      ? 'на фоне гемодиализа — повышенная поддерживающая доза (КР 2024)'
      : 'без гемодиализа (КР 2024); при гемодиализе доза выше — выберите «На фоне гемодиализа»',
    'цель — этанол в крови 1–2 г/л, контроль каждые 1–2 ч; скорость корректировать по уровню',
  ];
  if (s.route === 'po') notes.push('КР 2024: путь внутрь технически проще и безопаснее');
  res.result5 = sentence(notes);
  return res;
};

