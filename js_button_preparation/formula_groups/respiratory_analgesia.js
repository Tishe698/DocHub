// Число из поля; пусто/не число → NaN (такой ввод не считается)
const num = (v) => {
  const n = typeof v === 'number' ? v : parseFloat(v);
  return Number.isFinite(n) ? n : NaN;
};
const validWeight = (w) => Number.isFinite(w) && w > 0;
const validAge = (a) => Number.isFinite(a) && a >= 0;

// Новорождённый — младше 1 мес. (возраст < 1/12 года, как его передаёт движок)
