import { choiceInput, routeInput, ROUTES } from '../routes';

// Возраст в месяцах из полей «полных лет + месяцев сверх лет» (как в antibiotics_antiallergic.js).
// Возвращает { months } или { error: 'текст' }.
const ageInMonths = (ageYears, ageMonths) => {
  const y = Math.max(0, parseFloat(ageYears) || 0);
  const m = Math.max(0, parseFloat(ageMonths) || 0);
  if (y > 0 && m >= 12) {
    return { error: 'Месяцы указываются сверх полных лет: от 0 до 11. Проверьте возраст.' };
  }
  return { months: y * 12 + m };
};

// Число для текста: запятая, без «хвоста» плавающей точки
const num = (x, digits = 2) => String(Number(x.toFixed(digits))).replace('.', ',');
const weightOf = (x) => parseFloat(x) || 0;
const capFirst = (s) => s.charAt(0).toUpperCase() + s.slice(1);
// В/м в одну мышцу — не больше 5 мл; больше — в две мышцы
const IM_MAX_ML = 5;
const imSplitNote = (ml) =>
  ml > IM_MAX_ML
    ? ` Объём ${num(ml, 1)} мл — больше 5 мл: разделить на две инъекции в разные мышцы.`
    : '';
// Примечания одной фразой: через «; », с заглавной буквы и точкой в конце
const sentence = (notes) => {
  const text = notes.join('; ');
  return text.charAt(0).toUpperCase() + text.slice(1) + '.';
};

const ADULT_MONTHS = 18 * 12;
// Дозировка «как у взрослых» у антибиотиков: с 12 лет и массы 50 кг (инструкции ГРЛС, КР 714_2)
const isAdultSized = (months, w) => months >= 12 * 12 && w >= 50;

// ГМИ на догоспитальном этапе — одинаково для всех антибиотиков (КР 58, разд. 3.1)
const GMI_WARNING =
  'Менингококковая инфекция (ГМИ) на догоспитальном этапе: антибиотик — только при геморрагической сыпи, налаженном сосудистом доступе и инфузии (риск инфекционно-токсического шока от бактерицидного препарата); без сыпи — только если госпитализация займёт больше 90 мин. Доз для скорой КР не задают: расчёт — по инструкции и КР стационара (КР «Менингококковая инфекция у детей», 2023).';

/** ------------------------------ Клемастин ------------------------------ **/

const CLEM_CONC = 1; // мг/мл — инструкция «Тавегил»
const CLEM_ADULT_MG = 2; // инструкция и КР 263_2: взрослым 2 мг
const CLEM_CHILD_MG_PER_KG = 0.0125; // 0,025 мг/кг/сут в 2 введения → 0,0125 мг/кг на введение
const CLEM_MIN_MONTHS = 12; // до 1 года противопоказан

const clemastine = ({ weight, ageYears, ageMonths, route = 'im' }) => {
  if (route !== 'im' && route !== 'iv') return {};
  const w = weightOf(weight);
  if (!(w > 0)) return {};
  const age = ageInMonths(ageYears, ageMonths);
  if (age.error) return { result4: age.error };
  const m = age.months;
  // Инструкция «Тавегил»: детям до 1 года противопоказан
  if (m < CLEM_MIN_MONTHS) return {};
  const adult = m >= ADULT_MONTHS;
  if (!adult && route === 'iv') {
    // Инструкция и КР 263_2: детям — только в/м
    return {
      result4: 'Детям в/в введение в инструкции не описано — только в/м. Выберите путь «в/м».',
    };
  }
  const notes = [];
  let mg;
  if (adult) {
    mg = CLEM_ADULT_MG;
  } else {
    mg = Math.min(w * CLEM_CHILD_MG_PER_KG, CLEM_ADULT_MG);
    notes.push(
      `ребёнку 0,025 мг/кг в сутки = ${num(w * 0.025, 3)} мг/сут, на одно введение половина`,
    );
    if (w * CLEM_CHILD_MG_PER_KG > CLEM_ADULT_MG) notes.push('достигнута взрослая доза 2 мг');
  }
  const out = {
    result1: mg,
    result2: mg / CLEM_CONC,
    // Инструкция «Тавегил»: в/в медленно 2–3 мин, можно развести 1:5 NaCl 0,9% или глюкозой 5%
    result3:
      route === 'iv'
        ? 'в/в медленно, не быстрее чем за 2–3 мин; можно развести 1:5 NaCl 0,9% или глюкозой 5%. Повтор — не ранее чем через 12 ч (2 раза в сутки).'
        : 'в/м. Повтор — не ранее чем через 12 ч (2 раза в сутки).',
  };
  if (notes.length) out.result4 = sentence(notes);
  return out;
};

/** ------------------------------ Цефотаксим ------------------------------ **/

const CEFOTAXIME_INDICATION = choiceInput(
  'Показание',
  [
    { value: 'general', label: 'Пневмония, другие инфекции' },
    { value: 'severe', label: 'Менингит, ГМИ, сепсис, эпиглоттит' },
  ],
  'general',
);
const CEFO_CONC = 250; // мг/мл: 1 г в 4 мл воды для инъекций (инструкции ГРЛС, в/м и в/в струйно)
const CEFO_MAX_SINGLE = 2000; // мг — взрослая разовая при тяжёлых инфекциях (Клафоран: 2 г каждые 6–8 ч)
const CEFO_MAX_DAY = 12000; // мг — инструкции ГРЛС
const CEFO_ADULT = { general: 1000, severe: 2000 };

const cefotaximeAdministration = (route, indication, ml) => {
  const parts = [];
  if (route === 'im') {
    parts.push(
      `В/м глубоко: 1 г в 4 мл воды для инъекций (250 мг/мл). Лидокаин 1% как растворитель — только в/м, не детям до 2,5 лет.${imSplitNote(ml)}`,
    );
    // КР 58: при шоке в/м введение не достигает системного эффекта
    if (indication === 'severe')
      parts.push('При шоке в/м не вводить — только в/в или внутрикостно.');
  } else {
    parts.push(
      `${capFirst(ROUTES[route])} струйно медленно, за 3–5 мин: 1 г в 4 мл воды для инъекций (250 мг/мл); быстрее 1 мин — риск аритмий. Или капельно: 1–2 г в 40–100 мл NaCl 0,9% или глюкозы 5% за 20–60 мин.`,
    );
  }
  return parts.join(' ');
};

const cefotaxime = ({ weight, ageYears, ageMonths, indication = 'general', route = 'iv' }) => {
  if (!['iv', 'io', 'im'].includes(route)) return {};
  if (indication !== 'general' && indication !== 'severe') return {};
  const w = weightOf(weight);
  if (!(w > 0)) return {};
  const age = ageInMonths(ageYears, ageMonths);
  if (age.error) return { result5: age.error };
  const m = age.months;
  const severe = indication === 'severe';
  const notes = [];
  const out = {};
  let dose;
  let interval;

  if (m < 1) {
    // Новорождённые (0 мес — первые 4 недели; дни жизни из месяцев не отличить).
    // КР 912_1, прил. А3.4 и единая инструкция РФ (ЛС-002118): 50 мг/кг/сут в 2–4 введения;
    // тяжёлые — 150–200 мг/кг/сут: 50 мг/кг каждые 8 ч — нижняя граница.
    // Инструкция «Клафоран»: недоношенным в первую неделю — каждые 12 ч.
    // Предел — взрослая разовая доза: защита от ошибки ввода массы
    if (severe) {
      dose = Math.min(w * 50, CEFO_MAX_SINGLE);
      interval = 'каждые 8 ч (150 мг/кг/сут; КР — 150–200 мг/кг/сут)';
      notes.push('недоношенным в первую неделю жизни — каждые 12 ч (инструкция «Клафоран»)');
    } else {
      dose = Math.min(w * 25, CEFO_MAX_SINGLE);
      interval = 'каждые 12 ч (50 мг/кг/сут)';
    }
    out.result1 = dose;
    notes.push('у новорождённых — цефалоспорин первой линии: совместим с кальцием (КР 912_1)');
  } else if (isAdultSized(m, w)) {
    // Инструкции ГРЛС: средняя тяжесть 1–2 г каждые 8–12 ч; тяжёлые 2 г каждые 6–8 ч,
    // менингит — 2 г каждые 4–8 ч, не более 12 г/сут
    dose = CEFO_ADULT[indication];
    interval = severe
      ? 'каждые 6 ч (8 г/сут); при менингите допустимо каждые 4 ч — не более 12 г/сут'
      : 'каждые 8–12 ч (2–3 г/сут); при более тяжёлом течении — 2 г на введение';
    out.result1 = dose;
    out.result3 = severe ? dose * 4 : dose * 3;
  } else {
    // Дети до 12 лет или до 50 кг: КР 714_2 и единая инструкция РФ — 100–150 мг/кг/сут в 2–4 введения;
    // тяжёлые (менингит, ГМИ, эпиглоттит) — до 200 мг/кг/сут (Клафоран, КР 352_2).
    // Предел разовой — 2 г (Клафоран: 1–2 г на введение). Скачок дозы на пороге «12 лет и 50 кг»
    // заложен в самих КР 714_2: старше 12 лет — 1 г 2 раза в сутки
    const perKg = 50;
    dose = Math.min(w * perKg, CEFO_MAX_SINGLE);
    const perDay = severe ? 4 : 3;
    if (w * perKg > CEFO_MAX_SINGLE)
      notes.push(
        `достигнут предел разовой дозы 2 г: ${num((dose * perDay) / w, 0)} мг/кг/сут при ${perDay} введениях`,
      );
    interval = severe
      ? 'каждые 6 ч (200 мг/кг/сут)'
      : 'каждые 8 ч (150 мг/кг/сут); допустимо каждые 12 ч — 100 мг/кг/сут';
    out.result1 = dose;
    out.result3 = Math.min(dose * perDay, CEFO_MAX_DAY);
  }
  out.result2 = dose / CEFO_CONC;
  out.result4 = `${capFirst(interval)}. ${cefotaximeAdministration(route, indication, out.result2)}`;
  if (notes.length) out.result5 = sentence(notes);
  return out;
};

/** ------------------------------ Бензилпенициллин ------------------------------ **/

const PENICILLIN_INDICATION = choiceInput(
  'Показание',
  [
    { value: 'general', label: 'Инфекции средней тяжести' },
    { value: 'severe', label: 'Менингит, ГМИ, сепсис' },
  ],
  'severe',
);
// Тысячи ЕД во флаконе и концентрация готового раствора (инструкции ГРЛС, разд. «Способ применения»)
const PEN_VIAL = 1000; // тыс. ЕД — флакон 1 млн ЕД
// тыс. ЕД/мл с учётом объёма порошка (около 0,4 мл на флакон 1 млн ЕД): в/м 1,6 мл растворителя →
// 2 мл; в/в струйно 4,6 мл → 5 мл. Инструкция ГРЛС: в/м 1–3 мл, в/в струйно 5–10 мл растворителя
const PEN_CONC = { im: 500, iv: 200 };
const PEN_MAX_SINGLE = 4000; // тыс. ЕД — 4 млн ЕД (взрослым при менингите 24 млн ЕД/сут, 6 введений)
const PEN_ADULT_GENERAL = 1000; // тыс. ЕД — 1 млн ЕД 4 раза в сутки (4–6 млн ЕД/сут)

const penicillin = ({ weight, ageYears, ageMonths, indication = 'severe', route = 'iv' }) => {
  if (route !== 'im' && route !== 'iv') return {};
  if (indication !== 'general' && indication !== 'severe') return {};
  const w = weightOf(weight);
  if (!(w > 0)) return {};
  const age = ageInMonths(ageYears, ageMonths);
  if (age.error) return { result5: age.error };
  const m = age.months;
  // Инструкции и КР РФ не дают доз новорождённым — расчёт не выполняем
  if (m < 1) {
    return {
      result5:
        'Новорождённым доза в инструкциях и КР РФ не указана — расчёт не выполняется. Препарат выбора у новорождённых — цефотаксим (КР «Сепсис новорождённых», 2025).',
    };
  }
  const notes = [];
  let dose;
  let perDay;
  let interval;
  if (indication === 'severe') {
    // Инструкции ГРЛС: по жизненным показаниям до 500 тыс. ЕД/кг/сут; проект КР (взрослые, 2020):
    // 300–400 тыс. ЕД/кг/сут каждые 4 ч. Нижняя граница — 50 тыс. ЕД/кг × 6 = 300 тыс. ЕД/кг/сут
    dose = Math.min(w * 50, PEN_MAX_SINGLE);
    if (w * 50 > PEN_MAX_SINGLE) notes.push('достигнута разовая доза 4 млн ЕД (24 млн ЕД/сут)');
    perDay = dose * 6;
    interval = 'каждые 4 ч (300 тыс. ЕД/кг/сут)';
  } else if (isAdultSized(m, w)) {
    dose = PEN_ADULT_GENERAL;
    perDay = dose * 4;
    interval = 'каждые 6 ч (4 млн ЕД/сут; по инструкции 4–6 млн ЕД/сут)';
  } else {
    // Инструкции ГРЛС: до 1 года 50–100 тыс. ЕД/кг/сут, старше 1 года — 50 тыс. ЕД/кг/сут, 4 введения
    const perKgDay = m < 12 ? 100 : 50;
    dose = Math.min((w * perKgDay) / 4, PEN_ADULT_GENERAL);
    perDay = dose * 4;
    interval = `каждые 6 ч (${perKgDay} тыс. ЕД/кг/сут)`;
  }
  const conc = PEN_CONC[route];
  const prep =
    route === 'im'
      ? `В/м: во флакон 1 млн ЕД — 1,6 мл воды для инъекций, NaCl 0,9% или новокаина 0,5%, получится около 2 мл (500 тыс. ЕД/мл).${imSplitNote(dose / conc)}`
      : 'В/в струйно медленно, за 3–5 мин: во флакон 1 млн ЕД — 4,6 мл воды для инъекций или NaCl 0,9%, получится около 5 мл (200 тыс. ЕД/мл). Или капельно: 2–5 млн ЕД в 100–200 мл NaCl 0,9% или глюкозы 5%.';
  // КР 58: при шоке в/м введение не достигает системного эффекта
  if (route === 'im' && indication === 'severe')
    notes.push('при шоке в/м не вводить — только в/в или внутрикостно');
  if (route === 'iv' && indication === 'severe')
    notes.push(
      'по инструкции в/в вводят 1–2 раза в сутки, остальные введения — в/м; режим в/в каждые 4 ч — по КР для менингита, в стационаре',
    );
  const out = {
    result1: dose,
    result2: dose / conc,
    result3: perDay,
    result4: `${capFirst(interval)}. ${prep} Готовить непосредственно перед введением. Флаконов по 1 млн ЕД на введение: ${Math.ceil(dose / PEN_VIAL - 1e-9)}.`,
  };
  if (notes.length) out.result5 = sentence(notes);
  return out;
};

