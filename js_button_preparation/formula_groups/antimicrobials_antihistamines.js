//    2021 (ID 352_2) — при эпиглоттите 100–200 мг/кг/сут; КР «Сепсис новорождённых» 2025 (ID 912_1),
//    прил. А3.4 — 50 мг/кг/сут, при тяжёлых инфекциях 150–200 мг/кг/сут в 2–4 введения;
//  - бензилпенициллин: инструкции ГРЛС «Бензилпенициллина натриевая соль» (Синтез, ЛС-000410;
//    Биосинтез, ЛС-001481) — дети до 1 года 50–100 тыс. ЕД/кг/сут, старше 1 года 50 тыс. ЕД/кг/сут,
//    при необходимости 200–300, по жизненным показаниям до 500 тыс. ЕД/кг/сут; взрослым при тяжёлых
//    инфекциях 10–20 млн ЕД/сут; проект КР «Менингококковая инфекция у взрослых» 2020 —
//    300–400 тыс. ЕД/кг/сут в/в каждые 4 ч;
//  - КР «Менингококковая инфекция у детей» 2023 (ID 58), разд. 3.1: антибиотик на догоспитальном
//    этапе — только при геморрагической сыпи, сосудистом доступе и налаженной инфузии; первая линия —
//    цефалоспорины III поколения; бензилпенициллин эмпирически используется редко. Доз для СМП
