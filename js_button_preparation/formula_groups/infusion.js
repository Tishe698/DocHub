// Округление для текстовых примечаний (числовые результаты округляет движок)
const r1 = (v) => String(Math.round(v * 10) / 10);

// Болюс изотонического кристаллоида при шоке/гиповолемии — общее правило для NaCl 0,9% и Рингера:
// 10 мл/кг, затем переоценка — ERC Guidelines 2021, Paediatric Life Support (цит. по NICE 2022 exceptional surveillance);
// взрослым — 500 мл за <15 мин — NICE CG174 «IV fluid therapy in adults in hospital» (2013, ред. 2017), разд. 1.3.
// Предел одного болюса 500 мл достигается при весе 50 кг, поэтому детская и взрослая ветки стыкуются.
const BOLUS_ML_PER_KG = 10;
const BOLUS_MAX_ML = 500;
const crystalloidBolus = (w) => {
  const raw = w * BOLUS_ML_PER_KG;
  const ml = Math.min(raw, BOLUS_MAX_ML);
  const capNote = raw > BOLUS_MAX_ML
    ? `Ограничено взрослым болюсом 500 мл (расчёт ${r1(raw)} мл). `
    : '';
  return { ml, capNote };
};

// Текст введения болюса по пути. Внутрикостно — ERC 2021 PLS: в/к доступ при неудаче в/в,
// дозы и объёмы те же; жидкость вводят шприцем или под давлением, самотёком скорость недостаточна.
const bolusHowText = (route) =>
  route === 'io'
    ? 'В/к: шприцем 20–50 мл (набрать — ввести) или под давлением через манжету; самотёком не идёт.'
    : 'В/в струйно.';

// Поле «Показание и путь» для кристаллоидов (NaCl 0,9%, Рингер): в/к — только у болюса при шоке
