// Путь входит в вариант, поэтому сочетание без утверждённой дозы (ДКА в/к) выбрать нельзя
// (контракт routes.js: предлагать только пути с утверждённой дозой). others — [{ value, label }] в/в.
const crystalloidChoice = (others) =>
  choiceInput('Показание и путь', [
    { value: 'shock-iv', label: `Шок / гиповолемия — ${ROUTES.iv}` },
    { value: 'shock-io', label: `Шок / гиповолемия — ${ROUTES.io}` },
    ...others.map((o) => ({ value: o.value, label: `${o.label} — ${ROUTES.iv}` })),
  ], 'shock-iv');

// Разбор варианта → { ind, route }. Пустое или прежнее значение 'shock' — шок в/в.
const parseCrystalloid = (value) => {
  if (value === 'shock-io') return { ind: 'shock', route: 'io' };
  if (!value || value === 'shock' || value === 'shock-iv') return { ind: 'shock', route: 'iv' };
  return { ind: value, route: 'iv' };
};

