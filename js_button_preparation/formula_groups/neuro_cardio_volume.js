import { choiceInput, routeInput } from '../routes';

const num = (x, digits = 2) => String(Number(x.toFixed(digits))).replace('.', ',');
const weightOf = (x) => parseFloat(x) || 0;
const ageOf = (a) => {
  const n = parseFloat(a);
  return Number.isFinite(n) && n >= 0 ? n : NaN;
};
const EPS = 1e-9;
const sentence = (notes) => {
  const text = notes.join('; ');
  return text.charAt(0).toUpperCase() + text.slice(1) + '.';
};

/** ------------------------------ Леветирацетам ------------------------------ **/

const LEV_CONC = 100; // мг/мл — концентрат «Кеппра»
const LEV_VIAL_MG = 500; // флакон 5 мл
const LEV_LOW = 40; // мг/кг — нижняя граница КР 741_1
const LEV_HIGH = 60; // мг/кг — верхняя граница КР 741_1
const LEV_MIN_AGE = 4; // инструкция ГРЛС: концентрат противопоказан до 4 лет
const levMax = (age) => (age >= 18 - EPS ? 4500 : 4000); // КР 741_1: взрослым 4500, детям до 4000 мг

const levetiracetam = ({ weight, ageYears, route = 'iv' }) => {
  if (route !== 'iv') return {};
  const w = weightOf(weight);
  if (!(w > 0)) return {};
  const age = ageOf(ageYears);
  if (!Number.isFinite(age) || age < LEV_MIN_AGE - EPS) return {};
  const max = levMax(age);
  const low = Math.min(w * LEV_LOW, max);
  const high = Math.min(w * LEV_HIGH, max);
  const notes = [];
  if (w * LEV_LOW > max) notes.push(`достигнут предел ${max} мг (КР)`);
  notes.push(
    'по КР 40–60 мг/кг; в расчёте нижняя граница, верхняя — по решению врача (в исследовании ESETT — 60 мг/кг)',
  );
  return {
    result1: low,
    result2: low / LEV_CONC,
    result3: high,
    result4: `В/в капельно за 15 мин: концентрат развести не менее чем в 100 мл NaCl 0,9%, Рингер-лактата или глюкозы 5%; не быстрее 500 мг/мин. Флаконов по 500 мг: ${Math.ceil(low / LEV_VIAL_MG - EPS)}.`,
    result5: sentence(notes),
  };
};

/** ------------------------------ Феназепам ------------------------------ **/

const PHENAZEPAM_CONC = 1; // мг/мл
const PHENAZEPAM_MAX_DAY = 10; // мг — инструкция ГРЛС и КР 784_1
// Инструкция ГРЛС: разовая начальная и средняя суточная по показанию; КР 784_1 — абстиненция
const PHENAZEPAM_INDICATION = choiceInput(
  'Показание',
  [
    { value: 'agitation', label: 'Возбуждение, тревога' },
    { value: 'withdrawal', label: 'Алкогольный абстинентный синдром' },
    { value: 'seizures', label: 'Серийные эпилептические припадки' },
  ],
  'agitation',
);
const PHENAZEPAM = {
  agitation: {
    dose: 0.5,
    plan: 'начальная 0,5–1 мг; средняя суточная 3–5 мг, в тяжёлых случаях 7–9 мг',
  },
  withdrawal: { dose: 0.5, plan: '0,5 мг 1 раз в сутки (КР «Синдром отмены алкоголя», 2024)' },
  seizures: { dose: 0.5, plan: 'начинать с 0,5 мг; средняя суточная 1–3 мг' },
};

const phenazepam = ({ ageYears, indication = 'agitation', route = 'im' }) => {
  if (route !== 'im' && route !== 'iv') return {};
  const p = PHENAZEPAM[indication];
  if (!p) return {};
  const age = ageOf(ageYears);
  // Инструкция ГРЛС: до 18 лет противопоказан
  if (!Number.isFinite(age) || age < 18 - EPS) return {};
  const notes = [p.plan];
  if (age >= 65) notes.push('пожилым — начинать с меньшей дозы и наблюдать за дыханием');
  return {
    result1: p.dose,
    result2: p.dose / PHENAZEPAM_CONC,
    result3: PHENAZEPAM_MAX_DAY,
    result4:
      route === 'iv'
        ? 'в/в струйно медленно (скорость в инструкции не указана), под контролем дыхания.'
        : 'в/м.',
    result5: sentence(notes),
  };
};

/** ------------------------------ Маннитол ------------------------------ **/

const MANNITOL_CONC = 0.15; // г/мл — раствор 15%
const MANNITOL_LOW = 0.25; // г/кг — КР 732 и КР 493: нижняя граница, доза при дислокации у детей
const MANNITOL_HIGH = 1; // г/кг — верхняя граница КР
const MANNITOL_MAX_DAY = 140; // г — КР 493: не более 140–180 г/сут, берём нижнюю границу

const mannitol = ({ weight, route = 'iv' }) => {
  if (route !== 'iv') return {};
  const w = weightOf(weight);
  if (!(w > 0)) return {};
  const g = Math.min(w * MANNITOL_LOW, MANNITOL_MAX_DAY);
  const high = Math.min(w * MANNITOL_HIGH, MANNITOL_MAX_DAY);
  const notes = [
    'в расчёте нижняя граница КР 0,25 г/кг; верхняя 1 г/кг — по решению врача',
    // Инструкция ГРЛС «Маннитол» (Красфарма), при внутричерепной гипертензии: не чаще раза в 6–8 ч
    'повтор не чаще чем через 6–8 ч (инструкция), под контролем диуреза, натрия и калия',
  ];
  if (w * MANNITOL_HIGH > MANNITOL_MAX_DAY) notes.push(`предел ${MANNITOL_MAX_DAY} г в сутки (КР)`);
  return {
    result1: g,
    result2: g / MANNITOL_CONC,
    result3: high,
    result4:
      'в/в капельно за 20–30 мин (в инструкциях РФ — медленно струйно или капельно). Раствор подогреть до 37 °C; кристаллы растворить, нагрев флакон до 50–70 °C, и остудить.',
    result5: sentence(notes),
  };
};

/** ------------------------------ Дигоксин ------------------------------ **/

// Дозы в мкг: 125 мкг читается точнее, чем «0.13 мг» после округления (узкое терапевтическое окно)
const DIGOXIN_CONC = 250; // мкг/мл — раствор 0,25 мг/мл
const DIGOXIN_MAX_DAY = 1000; // мкг — инструкция ГРЛС: не более 1 мг/сут (строже КР ФП 1,5 мг за 24 ч)
const DIGOXIN_RISK = choiceInput(
  'Функция почек и риск',
  [
    { value: 'standard', label: 'Без особенностей' },
    {
      value: 'reduced',
      label: 'Клиренс креатинина ниже 50 мл/мин или низкий калий',
    },
  ],
  'standard',
);
// КР 156 (2024): первая доза 0,25–0,5 мг, при почечной недостаточности 0,0625–0,125 мг; берём нижние
// границы как самый осторожный вариант
const DIGOXIN_DOSE = { standard: 250, reduced: 125 }; // мкг

const DIGOXIN_ELDERLY = 70; // лет — инструкции ГРЛС и КР 156: пожилым дозу снижать
// Инструкция ГРЛС: при снижении функции почек уменьшают и нагрузочную дозу — в сниженном режиме
// предел за сутки вдвое меньше (500 мкг)
const DIGOXIN_MAX_DAY_REDUCED = 500;

const digoxin = ({ ageYears, risk = 'standard', route = 'iv' }) => {
  if (route !== 'iv') return {};
  if (!DIGOXIN_DOSE[risk]) return {};
  const age = ageOf(ageYears);
  // Детские в/в схемы в инструкциях РФ противоречат друг другу — детям не считаем
  if (!Number.isFinite(age) || age < 18 - EPS) return {};
  const reduced = risk === 'reduced' || age >= DIGOXIN_ELDERLY;
  const dose = reduced ? DIGOXIN_DOSE.reduced : DIGOXIN_DOSE.standard;
  const notes = [
    reduced
      ? `сниженная доза 125 мкг${risk === 'reduced' ? '' : ' — возраст 70 лет и старше'} (КР «Хроническая сердечная недостаточность», 2024: 62,5–125 мкг); сначала скорректировать калий`
      : 'первая доза 250 мкг — нижняя граница КР (250–500 мкг)',
    'только тем, кто не получал сердечные гликозиды последние 2 недели',
  ];
  return {
    result1: dose,
    result2: dose / DIGOXIN_CONC,
    result3: reduced ? DIGOXIN_MAX_DAY_REDUCED : DIGOXIN_MAX_DAY,
    result4: `в/в медленно за 10–20 мин; ${num(dose / DIGOXIN_CONC, 2)} мл развести не менее чем в 4 раза (NaCl 0,9% или глюкоза 5%) — иначе осадок. Повтор через 4–8 ч по частоте сердечных сокращений.`,
    result5: sentence(notes),
  };
};

/** ------------------------------ Гелофузин ------------------------------ **/

const GELO_BOLUS = 500; // мл — инструкция ГРЛС: экстренно 500 мл
const GELO_MAX = 1000; // мл — КР 119_3: модифицированный желатин не более 1000 мл
const GELO_ML_PER_KG = 30; // мл/кг — КР 119_3: коллоиды до 30 мл/кг

const gelofusine = ({ weight, ageYears, route = 'iv' }) => {
  if (route !== 'iv') return {};
  const w = weightOf(weight);
  if (!(w > 0)) return {};
  const age = ageOf(ageYears);
  // Инструкция ГРЛС: детских доз нет
  if (!Number.isFinite(age) || age < 18 - EPS) return {};
  const max = Math.min(GELO_MAX, w * GELO_ML_PER_KG);
  const bolus = Math.min(GELO_BOLUS, max);
  const notes = [
    'начинать с кристаллоидов; коллоид — если их недостаточно (КР)',
    `не более ${num(max, 0)} мл: желатин — до 1000 мл, коллоиды — до 30 мл/кг (КР «Послеродовое кровотечение», 2025)`,
  ];
  return {
    result1: bolus,
    result2: max,
    result3:
      'в/в капельно: первые 20–30 мл медленно (анафилактоидная реакция), затем по давлению, пульсу и диурезу; экстренно — 500 мл быстро под давлением, раствор согреть и удалить воздух из контейнера.',
    result4: sentence(notes),
  };
};

