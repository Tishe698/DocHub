//    нагрузочная 150–300 мг разжевать;
//  - фуросемид: инструкция ГРЛС «Фуросемид» р-р 10 мг/мл (Р N003668/01; rlsnet) — взрослым 20–40 мг в/в,
//    детям 1 мг/кг/сут, не более 20 мг/сут; в/в не быстрее 4 мг/мин; в/м — только в исключительных случаях;
//  - инсулин короткого действия: «Алгоритмы специализированной медицинской помощи больным СД», 11-й
//    выпуск, 2023 (Дедов И.И. и др.; DOI 10.14341/DM13042), разд. «ДКА» — взрослые; КР МЗ РФ «Сахарный
//    диабет 1 типа у детей» 2025 (ID 287) — дети;
//  - глюкагон: инструкция ГРЛС «ГлюкаГен 1 мг ГипоКит» (Ново Нордиск); КР «СД 1 типа у детей» 2025;
//  - ондансетрон: инструкция ГРЛС «Ондансетрон» р-р 2 мг/мл (Р-Фарм; Зофран); внутрь при рвоте на фоне
//    гастроэнтерита у детей — вне инструкции РФ: ESPGHAN/ESPID 2014, Freedman et al., NEJM 2006.

import { choiceInput, routeInput, ROUTES } from '../routes';

// Число для текста примечания: запятая, без «хвоста» плавающей точки
const num = (x, digits = 2) => String(Number(x.toFixed(digits))).replace('.', ',');
const toNum = (x) => parseFloat(x);
const weightOf = (x) => toNum(x) || 0;
// Возраст из поля: неотрицательное число или NaN
const ageOf = (a) => {
  const n = toNum(a);
  return Number.isFinite(n) && n >= 0 ? n : NaN;
};
// Сравнение возраста в долях года без ошибки плавающей точки (1/12 из движка)
const EPS = 1e-9;
// Примечания одной фразой: через «; », с заглавной буквы и точкой в конце
const sentence = (notes) => {
  const text = notes.join('; ');
  return text.charAt(0).toUpperCase() + text.slice(1) + '.';
};

// Взрослый — 18 лет и старше (как в группе «Реанимационные»: ERC 2021 — детские алгоритмы до 18 лет)
const ADULT_AGE = 18;
const isAdult = (age) => Number.isFinite(age) && age >= ADULT_AGE - EPS;

// Поле «Показание и путь»: варианты — только допустимые пары показание + путь.
// options: [{ value, indication, route (код ROUTES или null), label }]; подпись — «Показание — путь».
const indicationRoute = (options, defaultValue) => {
  const byValue = {};
  const choices = options.map((o) => {
    if (o.route && !ROUTES[o.route]) throw new Error(`indicationRoute: неизвестный путь «${o.route}»`);
    byValue[o.value] = o;
    return { value: o.value, label: o.route ? `${o.label} — ${ROUTES[o.route]}` : o.label };
  });
  const input = choiceInput('Показание и путь', choices, defaultValue);
  const parse = (value) => byValue[value] || byValue[input.default];
  return { input, parse };
};

