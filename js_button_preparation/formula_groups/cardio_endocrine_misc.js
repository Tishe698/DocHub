// Инструкция ГРЛС: детям 0,1 мг/кг, не более 4 мг; взрослым 4 мг
const OND_MAX_MG = 4;

// Freedman et al., NEJM 2006 (ESPGHAN/ESPID 2014): 8–15 кг 2 мг, >15–30 кг 4 мг, >30 кг 8 мг
const ondansetronPoMg = (w) => {
  if (w < 8) return null;
  if (w <= 15) return 2;
  if (w <= 30) return 4;
  return 8;
};

const ondansetron = (w, age, indication, route) => {
  if (!Number.isFinite(age)) return {};
  const adult = isAdult(age);
  if (indication === 'gastro') {
    // Только дети 6 мес – 17 лет, масса от 8 кг
    if (adult || age < 0.5 - EPS) return {};
    const mg = ondansetronPoMg(w);
    if (!mg) return {};
    return {
      result1: mg,
      result3: 'внутрь однократно; через 15–30 мин — начать пероральную регидратацию.',
      result4:
        mg === 2
          ? '2 мг — ½ таблетки 4 мг (если таблетку можно делить). Вне инструкции РФ (ESPGHAN 2014).'
          : `${mg} мг — ${mg === 4 ? '1 таблетка 4 мг' : '1 таблетка 8 мг'}. Вне инструкции РФ (ESPGHAN 2014).`,
    };
  }
  // Инструкция ГРЛС: ПОТР — противопоказано до 1 мес
  if (age < 1 / 12 - EPS) return {};
  if (route === 'im' && !adult) return {};
  const mgRaw = adult ? OND_MAX_MG : w * 0.1;
  const mg = Math.min(mgRaw, OND_MAX_MG);
  const res = { result1: mg, result2: mg / 2 };
  res.result3 =
    route === 'im'
      ? 'в/м однократно, без разведения.'
      : 'в/в медленно, не менее 30 с, без разведения (до 8 мг разводить не нужно).';
  const notes = [];
  if (adult) notes.push('Взрослым 4 мг однократно');
  else if (mgRaw > OND_MAX_MG) notes.push('Достигнут предел 4 мг');
  // Инструкция ГРЛС: доза указана для ПОТР и тошноты при химио- и лучевой терапии
  notes.push('доза — по инструкции РФ для послеоперационной тошноты и рвоты (и при химио- и лучевой терапии); при другой тошноте — вне инструкции');
  res.result4 = sentence(notes);
  return res;
};

