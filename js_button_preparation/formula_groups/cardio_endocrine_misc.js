const LIDOCAINE = indicationRoute(
  [
    // Инструкция ГРЛС «Лидокаин» (Биохимик): желудочковые тахиаритмии — в/в струйно, затем инфузия
    { value: 'vt-iv', indication: 'vt', route: 'iv', label: 'Желудочковая тахикардия с пульсом' },
    // ERC 2021 ALS/PLS: при СЛР — в/в или в/к, если нет амиодарона
    { value: 'cpr-iv', indication: 'cpr', route: 'iv', label: 'СЛР (ФЖ/ЖТ без пульса), нет амиодарона' },
    { value: 'cpr-io', indication: 'cpr', route: 'io', label: 'СЛР (ФЖ/ЖТ без пульса), нет амиодарона' },
    // Инфильтрационная анестезия: путь не из ROUTES — считается только максимальная доза
    { value: 'local', indication: 'local', route: null, label: 'Местная анестезия — максимальная доза' },
  ],
  'vt-iv'
);

const LIDO_CONC = 20; // мг/мл — раствор 2%
// Предел болюса 100 мг: инструкция ГРЛС (Биохимик) — «обычно 50–100 мг»; ERC 2021 ALS — 100 мг
const LIDO_BOLUS_MAX = 100;
// Инструкция ГРЛС «Лидокаин» (Органика, ЛП-№(004403)-(РГ-RU)): местная анестезия взрослым и подросткам
// 12–18 лет — не более 4,5 мг/кг и не более 300 мг на введение
const LIDO_LOCAL_MAX_MG = 300;
const lidoLocalPerKg = (age) => (Number.isFinite(age) && age >= 12 - EPS ? 4.5 : 3);

// Детская поддерживающая инфузия — одна для ЖТ с пульсом и для СЛР после восстановления кровообращения.
// Инструкция ГРЛС «Лидокаин» (Биохимик): детям «максимальная доза 30 мкг/кг/мин (20–50 мкг/кг/мин)» —
// берём 20–30, более строгий предел инструкции РФ (PALS 2020 допускает до 50). Верхняя граница в мг/ч —
// не выше взрослой инфузии 4 мг/мин = 240 мг/ч (та же инструкция: взрослым 1–4 мг/мин, не более 300 мг
// за 1 ч): у подростка с большой массой детский расчёт не превышает взрослый.
const LIDO_ADULT_INF_MAX_MG_H = 240;
const lidoChildInfusionText = (w) => {
  const loRaw = w * 0.02 * 60;
  const hiRaw = w * 0.03 * 60;
  const lo = Math.min(loRaw, LIDO_ADULT_INF_MAX_MG_H);
  const hi = Math.min(hiRaw, LIDO_ADULT_INF_MAX_MG_H);
  const range = lo === hi ? `${num(hi, 1)} мг/ч` : `${num(lo, 1)}–${num(hi, 1)} мг/ч`;
  const cap = hiRaw > LIDO_ADULT_INF_MAX_MG_H
    ? `; ограничено взрослой скоростью 4 мг/мин = 240 мг/ч (расчёт ${num(hiRaw, 1)} мг/ч)`
    : '';
  return `инфузия 20–30 мкг/кг/мин = ${range} (инструкция РФ: детям не более 30 мкг/кг/мин; PALS 2020 допускает до 50)${cap}`;
};

const lidocaineBolus = (w, age, indication, route) => {
  const adult = isAdult(age);
  const mgRaw = w * 1;
  // СЛР у взрослых — 100 мг независимо от массы (ERC 2021 ALS); остальные — 1 мг/кг, не более 100 мг
  const mg = indication === 'cpr' && adult ? LIDO_BOLUS_MAX : Math.min(mgRaw, LIDO_BOLUS_MAX);
  const res = { result1: mg, result2: mg / LIDO_CONC };
  const notes = [];
  if (indication === 'cpr') {
    // ERC 2021 ALS/PLS: болюс, затем промывание; взрослым повторно 50 мг после 5-го разряда
    res.result3 = `${ROUTES[route]} струйно, затем промыть NaCl 0,9%.`;
    res.result4 = adult
      ? 'Взрослым 100 мг независимо от веса; после 5-го разряда — ещё 50 мг (ERC 2021 ALS).'
      : `Детям 1 мг/кг, не более 100 мг (ERC 2021 PLS); после восстановления кровообращения — ${lidoChildInfusionText(w)}.`;
    if (!adult && mgRaw > LIDO_BOLUS_MAX) notes.push('достигнут предел 100 мг на введение');
  } else {
    // Инструкция ГРЛС (Биохимик): нагрузочная доза за 2–4 мин (25–50 мг/мин), сразу — инфузия
    res.result3 = 'в/в медленно за 2–4 мин (25–50 мг/мин) под контролем ЭКГ и АД.';
    if (adult) {
      // Инструкция ГРЛС: взрослым 1–1,5 мг/кг, инфузия 1–4 мг/мин, не более 300 мг за 1 ч и 2000 мг в сутки
      res.result4 =
        'Сразу после болюса — инфузия 1–4 мг/мин; повторный болюс ½–⅓ нагрузочной дозы через 8–10 мин. Не более 300 мг за 1 ч и 2000 мг в сутки.';
      notes.push('Взрослым 1–1,5 мг/кг (инструкция РФ), расчёт по нижней границе');
    } else {
      // Инструкция ГРЛС (Биохимик): детям 1 мг/кг, затем инфузия — см. lidoChildInfusionText
      const inf = lidoChildInfusionText(w);
      res.result4 = `${inf.charAt(0).toUpperCase()}${inf.slice(1)}.`;
    }
    if (mgRaw > LIDO_BOLUS_MAX && !(indication === 'cpr' && adult)) notes.push('достигнут предел 100 мг на введение');
  }
  notes.push('объём — по раствору 2% (20 мг/мл)');
  res.result5 = sentence(notes);
  return res;
};

const lidocaineLocal = (w, age) => {
  const perKg = lidoLocalPerKg(age);
  const mgRaw = w * perKg;
  const mg = Math.min(mgRaw, LIDO_LOCAL_MAX_MG);
  const notes = [];
  if (perKg === 4.5) notes.push('с 12 лет и взрослым — 4,5 мг/кг, не более 300 мг (инструкция РФ)');
  else notes.push('до 12 лет — 3 мг/кг (BNFc; в инструкции РФ предела в мг/кг нет)');
  if (mgRaw > LIDO_LOCAL_MAX_MG) notes.push('достигнут предел 300 мг');
  // Инструкция ГРЛС (Биохимик): до 6 лет — с осторожностью; у детей метаболизм замедлен
  if (!Number.isFinite(age) || age < 6) notes.push('до 6 лет — с осторожностью, по возможности меньше');
  // Свои ключи (result6–result10): подписи «Максимальная доза…» не путаются с болюсом антиаритмика
  return {
    result6: mg,
    result7: mg / 20,
    result8: mg / 10,
    // Инструкция ГРЛС (Биохимик): проводниковая анестезия взрослым — не более 200 мг (10 мл 2%)
    result9:
      'Предел на всю процедуру, без вазоконстриктора. Перед введением — аспирационная проба. Проводниковая анестезия взрослым — не более 200 мг (10 мл 2%).',
    result10: sentence(notes),
  };
};

