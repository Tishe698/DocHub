import { routeInput, choiceInput } from '../routes';

// Число для текста примечания: без «хвоста» плавающей точки
const num = (x, digits = 2) => String(Number(x.toFixed(digits)));
const ml1 = (x) => num(x, x < 1 ? 2 : 1);
const age = (a) => {
  const n = parseFloat(a);
  return Number.isFinite(n) && n >= 0 ? n : NaN;
};
// Сравнение возраста в долях года без ошибки плавающей точки (1/12 из движка)
const EPS = 1e-9;

// Мидазолам при ЭС: разовая доза детям до 5 лет не более 5 мг, с 5 лет и взрослым — 10 мг (КР 2022, 3.2)
const midazolamCap = (a) => (a < 5 ? 5 : 10);

// Защёчно — КР 2022, разд. 3.2 (возрастные дозы): 3 мес–1 год 2.5 мг; 1–5 лет 5 мг;
// 5–10 лет 7.5 мг; 10–18 лет и взрослым 10 мг. Младше 3 мес дозы в КР нет.
export const buccalMidazolamMg = (a) => {
  if (!(a >= 0.25 - EPS)) return null;
  if (a < 1) return 2.5;
  if (a < 5) return 5;
  if (a < 10) return 7.5;
  return 10;
};

