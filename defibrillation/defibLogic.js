// Монофазный аппарат: КР РФ 2025 и AHA — дефибрилляция 360 Дж; кардиоверсия — ориентиры AHA 2010
// (ФП 200 Дж, ЖТ и ТП/НЖТ 100 Дж), в рекомендациях 2025 монофазных доз нет; повышение — по типичным
// ступеням монофазных аппаратов
const MONO_TARGET = { vf: 360, af: 200, vt: 100, svt: 100 };
const MONO_STEPS = [50, 100, 200, 300, 360];

const fmtNum = (x, d = 1) => String(Number(x.toFixed(d))).replace('.', ',');
// Неразрывный пробел: «360 Дж» не разрывается переносом строки
const J = (j) => `${j} Дж`;
const chain = (list) => list.map((e) => J(e)).join(' → ');

// «джоуль / джоуля / джоулей» — для диктора
export const joules = (n) => {
  const i = Math.round(n);
  const d = i % 10;
  const dd = i % 100;
  if (d === 1 && dd !== 11) return 'джоуль';
  if (d >= 2 && d <= 4 && (dd < 12 || dd > 14)) return 'джоуля';
  return 'джоулей';
};
const spokenJ = (n) => `${n} ${joules(n)}`;
const spokenChain = (list) =>
  list.length > 1
    ? `${list.slice(0, -1).join(', затем ')}, затем ${spokenJ(list[list.length - 1])}`
    : spokenJ(list[0]);

// Ступени аппарата не выше max (если задан); null — не опубликованы
const usableSteps = (steps, max) => {
  if (!Array.isArray(steps) || !steps.length) return null;
  const sorted = [...steps].sort((a, b) => a - b);
  const capped = max ? sorted.filter((x) => x <= max + 1e-9) : sorted;
  return capped.length ? capped : null;
};

// Ступень аппарата для расчётной энергии. mode: 'up' — не ниже цели (нет такой — наибольшая),
// 'down' — не выше (нет — наименьшая), 'near' — ближайшая (при равном расстоянии — tie: 'down' | 'up').
// Без опубликованных ступеней — целое число Дж в пределах максимума.
export function pickStep(steps, target, mode = 'near', max = null, tie = 'down') {
  if (!(target > 0)) return null;
  const list = usableSteps(steps, max);
  if (!list) {
    const r =
      mode === 'up'
        ? Math.ceil(target - 1e-9)
        : mode === 'down'
          ? Math.floor(target + 1e-9)
          : Math.round(target);
    return max ? Math.min(Math.max(r, 1), max) : Math.max(r, 1);
  }
  if (mode === 'up') return list.find((x) => x >= target - 1e-9) ?? list[list.length - 1];
  if (mode === 'down') {
    const below = list.filter((x) => x <= target + 1e-9);
    return below.length ? below[below.length - 1] : list[0];
  }
  let best = list[0];
  for (const x of list) {
    const dx = Math.abs(x - target);
    const db = Math.abs(best - target);
    if (dx < db - 1e-9 || (tie === 'up' && Math.abs(dx - db) <= 1e-9)) best = x;
  }
  return best;
}

// Первая энергия взрослому на этом аппарате. null — «максимум аппарата», когда он неизвестен.
export function adultFirstEnergy(scenarioKey, device) {
  const max = deviceMax(device);
  if (device.waveform === 'monophasic') {
    return pickStep(device.steps, MONO_TARGET[scenarioKey], 'near', max);
  }
  const t = ADULT_TARGET[scenarioKey];
  if (!t) return null;
  if (t.first === 'max') return max; // ФП: максимум аппарата (ERC 2025); неизвестен — null
  if (scenarioKey === 'vf') {
    // ERC 2025: рекомендации производителя неизвестны — максимальная энергия
    if (device.unknown) return max;
    // ERC 2025: не менее 150 Дж; если производитель рекомендует больше — его значение
    return pickStep(device.steps, Math.max(150, device.adultDefibFirst || 150), 'up', max);
  }
  // Кардиоверсия ЖТ, ТП/НЖТ: нижняя граница диапазона, ступень не ниже неё и не выше верхней границы
  const step = pickStep(device.steps, t.first, 'up', max);
  return t.firstMax && step > t.firstMax ? pickStep(device.steps, t.firstMax, 'down', max) : step;
}

// Повторные разряды при дефибрилляции взрослого: протокол производителя или выше до максимума аппарата
function defibEscalation(device, first) {
  const max = deviceMax(device);
  if (device.adultEscalation) return device.adultEscalation.filter((e) => e > first);
  const list = usableSteps(device.steps, max);
  if (!list) return max && max > first ? [max] : [];
  const higher = list.filter((x) => x > first);
  if (!higher.length) return [];
  const top = higher[higher.length - 1];
  const mid = higher.find((x) => x >= first + 50) ?? top;
  return [...new Set([mid, top])];
}

// Повторные попытки кардиоверсии: ступенчато (ERC 2025) — каждая следующая примерно в 1,5 раза выше
function syncEscalation(steps, first, max) {
  const list = usableSteps(steps, max);
  if (!list || !first) return [];
  const out = [];
  let cur = first;
  for (let i = 0; i < 2; i += 1) {
    const higher = list.filter((x) => x > cur);
    if (!higher.length) break;
    const nextStep = higher.find((x) => x >= cur * 1.4 - 1e-9) ?? higher[higher.length - 1];
    out.push(nextStep);
    cur = nextStep;
  }
  return out;
}

