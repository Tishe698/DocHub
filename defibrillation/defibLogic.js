/**
 * План для экрана.
 * @param scenario — ключ SCENARIOS; device — профиль из devices.js; group — 'adult' | 'child';
 *   weightKg — масса (число или строка; для ребёнка нужна)
 * @returns null | {
 *   mode: 'defib' | 'sync' | 'none' | 'pace' | 'aed' | 'nosync',
 *   first: число Дж | null, firstText, nextText, calcText, pads, notes: [строки],
 *   spoken: текст для диктора, needWeight, smallChild
 * }
 */
export function shockPlan({ scenario, device, group, weightKg }) {
  const sc = scenarioByKey(scenario);
  if (!sc || !device) return null;
  const child = group === 'child';
  const w = Number(weightKg);
  const hasWeight = Number.isFinite(w) && w >= CHILD_WEIGHT_MIN && w <= CHILD_WEIGHT_MAX;
  const smallChild = child && hasWeight && w < PEDIATRIC_PAD_MAX_KG;
  const base = {
    mode: sc.mode,
    first: null,
    firstText: '',
    nextText: null,
    calcText: null,
    pads: null,
    notes: [],
    spoken: '',
    needWeight: false,
    smallChild,
  };

  if (sc.mode === 'none') {
    return { ...base, firstText: 'Разряд не наносить', spoken: 'Разряд не наносить' };
  }

  if (sc.mode === 'pace') {
    if (device.pacing === false) {
      return {
        ...base,
        firstText: 'Этот аппарат не умеет кардиостимуляцию',
        notes: [
          'Нужен дефибриллятор-монитор с наружной кардиостимуляцией (например, LIFEPAK 15, ZOLL R Series, Mindray BeneHeart, corpuls3).',
        ],
        spoken: 'Разряд не наносить. Этот аппарат не умеет кардиостимуляцию',
      };
    }
    const notes = [];
    if (device.pacing === 'option')
      notes.push(
        'Кардиостимуляция у этой модели — опция: проверьте, есть ли она в вашем аппарате.',
      );
    if (device.pacing === undefined)
      notes.push('Есть ли у аппарата кардиостимуляция — проверьте по инструкции.');
    if (child)
      notes.push(
        'Детям стимуляция — только при полной АВ-блокаде или дисфункции синусового узла; при брадикардии от гипоксии сначала кислород и вентиляция (ERC 2025).',
      );
    return {
      ...base,
      firstText: 'Разряд не наносить — кардиостимуляция',
      pads: PADS_PACING,
      notes,
      spoken: 'Разряд не наносить. Кардиостимуляция, если атропин не помог',
    };
  }

  if (device.aedOnly) {
    if (sc.mode === 'sync') {
      return {
        ...base,
        mode: 'nosync',
        firstText: 'Этот аппарат не умеет кардиоверсию',
        notes: [
          'Автоматический дефибриллятор не делает синхронизированный разряд — нужен ручной дефибриллятор-монитор с режимом SYNC.',
        ],
        spoken: 'Этот аппарат не умеет кардиоверсию, нужен дефибриллятор-монитор',
      };
    }
    const notes = [];
    let nextText;
    let pads;
    if (child && !hasWeight) {
      // ERC PLS 2025: детский режим или детские электроды до 25 кг (около 8 лет)
      nextText = `До 25 кг (около 8 лет) — детские электроды: ${chain(device.aedChild)}; старше — взрослые: ${chain(device.aedAdult)}`;
      pads = PADS_UNKNOWN_CHILD;
    } else {
      const energies = smallChild ? device.aedChild : device.aedAdult;
      nextText = `${smallChild ? 'Детские электроды' : 'Взрослые электроды'}: ${chain(energies)}`;
      pads = smallChild ? PADS_CHILD : PADS_ADULT;
    }
    if (child && (smallChild || !hasWeight))
      notes.push(
        'Если детских электродов или детского режима нет — используйте взрослые: польза разряда выше риска (ERC 2025).',
      );
    if (device.note) notes.push(device.note);
    return {
      ...base,
      mode: 'aed',
      firstText: 'Аппарат выбирает энергию сам',
      nextText,
      pads,
      notes,
      spoken: 'Автоматический режим: аппарат выбирает энергию сам',
    };
  }

  if (child && !hasWeight) {
    return {
      ...base,
      firstText: 'Укажите массу ребёнка',
      needWeight: true,
      spoken: 'Укажите массу ребёнка',
    };
  }

  const max = deviceMax(device);
  const steps = smallChild && device.childSteps ? device.childSteps : device.steps;
  const stepMax = smallChild && device.childSteps ? Math.max(...device.childSteps) : max;
  const notes = [];
  let first;
  let next = [];
  let calcText = null;
  let nextText = null;

  if (child) {
    // ERC PLS 2025: дефибрилляция 4 Дж/кг (не выше взрослой дозы); кардиоверсия 1 Дж/кг, затем 2 Дж/кг
    // (КР «СВТ у детей» 2025: 0,5–1–2 Дж/кг; ERC — удваивать до 4 Дж/кг)
    const adultFirst = adultFirstEnergy(sc.key, device) || 150;
    if (sc.mode === 'defib') {
      const target = 4 * w;
      if (target >= adultFirst) {
        // Подросток: доза не меньше взрослой — взрослая энергия и взрослые повторные разряды
        first = adultFirst;
        next = defibEscalation(device, first);
        calcText = `4 Дж/кг × ${fmtNum(w)} кг = ${fmtNum(target, 0)} Дж — не меньше взрослой дозы: энергия как у взрослого`;
      } else {
        // Ступень, ближайшая к 4 Дж/кг (при равенстве — большая), но не выше взрослой дозы
        first = pickStep(steps, target, 'near', Math.min(stepMax || adultFirst, adultFirst), 'up');
        const perKg = first / w;
        calcText = `4 Дж/кг × ${fmtNum(w)} кг = ${fmtNum(target, 1)} Дж → на аппарате ${J(first)} (${fmtNum(perKg, 1)} Дж/кг)`;
        if (perKg > 8) {
          notes.push(
            `Наименьшая ступень аппарата ${J(first)} — это ${fmtNum(perKg, 1)} Дж/кг, больше 8 Дж/кг. Нужен аппарат с меньшими ступенями или детский режим.`,
          );
        } else if (perKg > 5 || perKg < 3) {
          notes.push(
            `Ближайшая ступень аппарата — ${fmtNum(perKg, 1)} Дж/кг (рекомендовано 4 Дж/кг; допустимо 2–8 Дж/кг).`,
          );
        }
        next = [first];
        notes.push(
          'Повторные разряды — та же энергия; если нужно больше 5 разрядов, можно повышать до 8 Дж/кг (не более 360 Дж).',
        );
      }
    } else {
      const cap = Math.min(stepMax || adultFirst, adultFirst);
      first = pickStep(steps, Math.min(w, adultFirst), 'near', cap);
      const perKg = first / w;
      calcText = `1 Дж/кг × ${fmtNum(w)} кг = ${fmtNum(w, 1)} Дж → на аппарате ${J(first)} (${fmtNum(perKg, 1)} Дж/кг)`;
      if (perKg > 4)
        notes.push(
          `Наименьшая ступень аппарата ${J(first)} — это ${fmtNum(perKg, 1)} Дж/кг, больше 4 Дж/кг: решение — за врачом.`,
        );
      // Вторая попытка — не меньше 2 Дж/кг (ступень вверх), но не выше 4 Дж/кг (ERC)
      let second = pickStep(steps, Math.min(2 * w, adultFirst), 'up', cap);
      if (second > 4 * w + 1e-9) {
        second = pickStep(steps, Math.min(2 * w, adultFirst), 'near', cap);
        if (second > 4 * w + 1e-9) second = null;
      }
      if (second && second <= first) {
        const list = usableSteps(steps, cap);
        const up = list ? list.find((x) => x > first) : null;
        second = up && up <= 4 * w + 1e-9 ? up : null;
      }
      if (second) {
        next = [second];
        calcText += `. Если не помогло — 2 Дж/кг (${fmtNum(2 * w, 0)} Дж) → ${J(second)}`;
      } else {
        notes.push('Следующая ступень аппарата больше 4 Дж/кг — повышать только по решению врача.');
      }
      notes.push('КР РФ: 0,5–1–2 Дж/кг; ERC 2025 допускает удваивать до 4 Дж/кг.');
    }
  } else if (device.waveform === 'monophasic') {
    // Монофазный: КР РФ 2025 — 360 Дж при дефибрилляции; кардиоверсия — ориентиры AHA 2010
    first = adultFirstEnergy(sc.key, device);
    if (sc.mode === 'sync') {
      next = syncEscalation(device.steps || MONO_STEPS, first, max);
      notes.push(
        'Монофазный аппарат: доз кардиоверсии в рекомендациях 2025 нет — ориентир AHA 2010, сверьтесь с инструкцией аппарата.',
      );
    }
  } else {
    first = adultFirstEnergy(sc.key, device);
    if (sc.mode === 'defib') next = first ? defibEscalation(device, first) : [];
    else if (sc.key !== 'af') next = syncEscalation(device.steps, first, max);
  }

  // Тексты результата
  const unknownSteps = !usableSteps(steps, stepMax);
  const firstText = first
    ? J(first)
    : sc.key === 'af'
      ? 'Максимум аппарата (не меньше 200 Дж)'
      : 'Максимум аппарата';
  const repeat = next.filter((e) => e !== first);
  if (sc.mode === 'defib') {
    if (repeat.length) nextText = `Повторные разряды: ${chain(repeat)}`;
    else if (!first) nextText = 'Повторные разряды: та же максимальная энергия';
    else if (unknownSteps && !child && device.waveform !== 'monophasic')
      nextText = 'Повторные разряды: выше, до максимума аппарата';
    else nextText = 'Повторные разряды: та же энергия';
  } else if (sc.key === 'af' && !child && device.waveform !== 'monophasic') {
    nextText = 'Повторно — та же максимальная энергия';
  } else if (repeat.length) {
    nextText = `Если не помогло: ${chain(repeat)}`;
  } else if (unknownSteps && !child) {
    nextText = 'Если не помогло — следующая ступень выше';
  }

  if (device.note) notes.push(device.note);
  if (sc.mode === 'defib' && !child && device.defibNote) notes.push(device.defibNote);

  const modeWords =
    sc.mode === 'defib'
      ? 'Дефибрилляция без синхронизации'
      : 'Кардиоверсия, включить синхронизацию';
  const spoken = [
    modeWords,
    first ? spokenJ(first) : firstText,
    repeat.length
      ? `${sc.mode === 'defib' ? 'Повторные' : 'Если не помогло'}: ${spokenChain(repeat)}`
      : null,
  ]
    .filter(Boolean)
    .join('. ');

  return {
    ...base,
    first: first || null,
    firstText,
    nextText,
    calcText,
    pads: smallChild ? PADS_CHILD : PADS_ADULT,
    notes,
    spoken,
  };
}

